function field(
  name: string,
  category: FieldClassification['category'],
  confidence: number,
  note?: string,
): FieldClassification {
  return { field: name, category, confidence, note }
}

function schemaType(name: string): SchemaField['type'] {
  if (/email/i.test(name)) return 'email'
  if (/date|received|withdrawn|timestamp|modified/i.test(name)) return 'date'
  if (/total|amount|value|balance/i.test(name)) return 'currency'
  if (/count|number|quantity/i.test(name)) return 'number'
  if (/consent/i.test(name)) return 'boolean'
  return 'string'
}

function schemaFor(fields: FieldClassification[], customer?: Customer): SchemaField[] {
  const fallbackFor = (name: string): string => {
    if (/email/i.test(name)) return customer?.email ?? 'contact@synthetic.example'
    if (/phone/i.test(name)) return customer?.phone ?? '+44 20 7946 0000'
    if (/name/i.test(name) && !/company/i.test(name)) return customer?.name ?? 'Synthetic contact'
    if (/company|organisation/i.test(name)) return customer?.company ?? 'Synthetic Company Ltd'
    if (/date|received|withdrawn|timestamp|modified/i.test(name)) return '2026-10-22'
    if (/total|amount|value|balance/i.test(name)) return '£2,480.00'
    if (/consent/i.test(name)) return 'true'
    if (/location|address/i.test(name)) return customer?.location ?? 'London'
    return '—'
  }

  return fields.map((entry) => ({
    field: entry.field,
    type: schemaType(entry.field),
    example: fallbackFor(entry.field),
    classification: entry.category,
  }))
}

interface DocumentSeed extends Omit<DocumentRecord, 'schema' | 'confidence'> {
  confidence?: number
}

function makeDocument(seed: DocumentSeed, customer?: Customer): DocumentRecord {
  const defaultConfidence =
    seed.reviewStatus === 'reviewed' ? 0.97 : seed.reviewStatus === 'needs-review' ? 0.78 : 0.94
  return {
    ...seed,
    confidence: seed.confidence ?? defaultConfidence,
    schema: schemaFor(seed.fields, customer),
  }
}

